"""How much does the spatial index speed up a "near me" query? Measures it with EXPLAIN ANALYZE.

Run from the repo root, with the database running and the pipeline loaded:
    python -m scripts.benchmark_spatial_index

The query: how many people live within 1 mile of a point (census blocks, 38,180 rows). It runs
for 20 points around Dallas County, several times each, first with the geography index and then
without it. "Without" drops the index inside a transaction and rolls back at the end, so the
database always ends up with its index. (The drop locks the table for the few seconds the test
takes, so don't run this against a database that's serving users.)

Writes the results to docs/spatial-index-benchmark.md.
"""

import json
import statistics
from datetime import date
from pathlib import Path

from sqlalchemy import Connection, text

from pipeline.db import create_db_engine

INDEX_NAME = "ix_census_blocks_geography"
ONE_MILE_M = 1609.344
POINTS = 20
RUNS_PER_POINT = 5
REPORT_PATH = Path(__file__).resolve().parents[1] / "docs" / "spatial-index-benchmark.md"

NEAR_ME_QUERY = """
SELECT count(*) AS blocks, sum(population) AS people
FROM census_blocks
WHERE ST_DWithin(center::geography, ST_SetSRID(ST_MakePoint(:lng, :lat), 4326)::geography, :radius)
"""

# A fixed, spread-out set of points: the inner point of every 32nd tract
POINTS_QUERY = text(
    """
    SELECT ST_X(point) AS lng, ST_Y(point) AS lat
    FROM (SELECT ST_PointOnSurface(geom) AS point, row_number() OVER (ORDER BY geoid) AS n
          FROM tracts) AS numbered
    WHERE n % 32 = 0
    LIMIT :limit
    """
)


def explain(connection: Connection, lng: float, lat: float) -> dict:
    """Run the query with EXPLAIN ANALYZE: Postgres runs it and reports what it did and how long
    it took inside the database (no network or Python time)."""
    plan = connection.execute(
        text(f"EXPLAIN (ANALYZE, FORMAT JSON) {NEAR_ME_QUERY}"),
        {"lng": lng, "lat": lat, "radius": ONE_MILE_M},
    ).scalar_one()
    return plan[0] if isinstance(plan, list) else json.loads(plan)[0]


def scan_types(node: dict) -> set[str]:
    """Every way the plan reads a table, e.g. {"Seq Scan"} or {"Bitmap Index Scan", ...}."""
    found = {node["Node Type"]} if "Scan" in node["Node Type"] else set()
    for child in node.get("Plans", []):
        found |= scan_types(child)
    return found


def measure(connection: Connection, points: list) -> dict:
    times, scans = [], set()
    for lng, lat in points:
        explain(connection, lng, lat)  # warm-up run, not counted (fills Postgres's caches)
        for _ in range(RUNS_PER_POINT):
            result = explain(connection, lng, lat)
            times.append(result["Execution Time"])
            scans |= scan_types(result["Plan"])
    return {"median_ms": statistics.median(times), "max_ms": max(times), "scans": sorted(scans)}


def main() -> None:
    engine = create_db_engine()
    with engine.connect() as connection:
        points = [tuple(row) for row in connection.execute(POINTS_QUERY, {"limit": POINTS})]
        lng, lat = points[0]
        example = connection.execute(
            text(NEAR_ME_QUERY), {"lng": lng, "lat": lat, "radius": ONE_MILE_M}
        ).one()
        with_index = measure(connection, points)

        # SQLAlchemy opened a transaction automatically for the queries above; end it, then
        # start the one the index will be dropped (and restored by rolling back) inside
        connection.rollback()
        transaction = connection.begin()
        try:
            connection.execute(text(f"DROP INDEX {INDEX_NAME}"))
            without_index = measure(connection, points)
        finally:
            transaction.rollback()  # puts the index back
    engine.dispose()

    speedup = without_index["median_ms"] / with_index["median_ms"]
    rows = [
        ("With index", with_index),
        ("Without index", without_index),
    ]
    table = "\n".join(
        f"| {label} | {result['median_ms']:.2f} ms | {result['max_ms']:.2f} ms | "
        f"{', '.join(result['scans'])} |"
        for label, result in rows
    )
    REPORT_PATH.parent.mkdir(exist_ok=True)
    REPORT_PATH.write_text(
        f"""# Spatial index benchmark

Generated by `python -m scripts.benchmark_spatial_index` on {date.today().isoformat()}.

**Query:** how many people live within 1 mile of a point, over the 38,180 census blocks:

```sql
{NEAR_ME_QUERY.strip()}
```

**Method:** {POINTS} points across Dallas County, {RUNS_PER_POINT} timed runs each (after one
warm-up), using `EXPLAIN ANALYZE`'s execution time (time inside Postgres only). "Without index"
drops `{INDEX_NAME}` inside a transaction that is rolled back afterwards.

| | Median | Slowest | How Postgres read the table |
| --- | --- | --- | --- |
{table}

**The index makes this query about {speedup:.0f}x faster.** Without it, Postgres reads all 38,180
blocks and measures the distance to each one (a sequential scan). With it, Postgres walks the
GIST index's tree of bounding boxes to find only the blocks near the point, then measures just
those.

Example: within 1 mile of ({lat:.4f}, {lng:.4f}) there are {example.blocks:,} census blocks with
{example.people:,} people.
"""
    )
    for label, result in rows:
        print(f"{label}: median {result['median_ms']:.2f} ms ({', '.join(result['scans'])})")
    print(f"Speedup: {speedup:.1f}x. Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
